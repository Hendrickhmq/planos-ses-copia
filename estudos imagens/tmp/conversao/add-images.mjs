import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile,FileBlob} from '@oai/artifact-tool';
const root='/Users/hendrick/Projetos/planos-ses/estudos imagens';
const path=`${root}/outputs/tabela-sus-candanga/Tabela SUS Candanga.xlsx`;
await fs.copyFile(path,`${root}/tmp/conversao/original.xlsx`);
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(path));
const source=wb.worksheets.getItemAt(0);
const before=await wb.render({sheetName:source.name,range:'A1:E10',scale:1,format:'png'});
await fs.writeFile(`${root}/tmp/conversao/before.png`,new Uint8Array(await before.arrayBuffer()));
const raw=source.getRange('A7:E2962').values;
const ophthalmic=new Set(['0211060011','0211060143','0211060178','0211060186','0211060267']);
function category(r){
 if(r[2]!=='SIA')return null;
 const [code,desc]=r;
 if(code==='0201010542')return 'Biópsia guiada por imagem';
 if(ophthalmic.has(code))return 'Imagem oftalmológica';
 if(code==='0501080090')return 'Ultrassonografia';
 if(code.startsWith('0210'))return 'Radiologia intervencionista';
 if(code.startsWith('0204')){
   if(desc.includes('MAMOGRAFIA'))return 'Mamografia e procedimentos associados';
   if(desc.includes('DENSITOMETRIA'))return 'Densitometria óssea';
   return 'Radiologia';
 }
 if(code.startsWith('0205'))return desc.startsWith('ECOCARDIOGRAFIA')?'Ecocardiografia':'Ultrassonografia';
 if(code==='0206010095'||code.startsWith('0208'))return 'Medicina nuclear';
 if(code.startsWith('0206'))return 'Tomografia computadorizada';
 if(code.startsWith('0207'))return 'Ressonância magnética';
 return null;
}
const rows=raw.filter(r=>category(r)).map(r=>[...r,category(r)]);
const s=wb.worksheets.add('Imagens ambulatoriais');
const end=rows.length+6;
s.showGridLines=false;
s.getRange(`A1:F${end}`).format.font={name:'Arial',size:10,color:'#202D3A'};
s.getRange(`A1:F${end}`).format.verticalAlignment='center';
s.getRange('A1').values=[['Imagens ambulatoriais']];
s.getRange('A1').format.font={name:'Arial',size:16,bold:true,color:'#17365D'};
s.getRange('A1:F1').format.rowHeight=30;
s.getRange('A2').values=[['Fonte: aba Tabela SUS Candanga, extraída de TABELA SUS CANGANGA OFICIAL.pdf. SES/DF. SEI 212117347.']];
s.getRange('A3').values=[['Recorte: modalidade SIA; diagnóstico por imagem e procedimentos explicitamente associados. Categorias atribuídas pela descrição e pelo código.']];
s.getRange('A4').values=[[`${rows.length} registros. Inclui imagem oftalmológica e biópsia guiada. Ofertas integradas (OCI), endoscopias e tratamentos não integram este recorte.`]];
s.getRange('A2:F4').format.font={name:'Arial',size:10,color:'#536477'};
s.getRange('A2:F4').format.rowHeight=21;
s.getRange(`A6:F${end}`).values=[['Código','Procedimento/Item','Modalidade','Valor SUS Candanga (R$)','Página do PDF','Categoria'],...rows];
s.getRange(`A7:A${end}`).setNumberFormat('@');
s.getRange(`D7:D${end}`).setNumberFormat('"R$" #,##0.00');
s.getRange(`E7:E${end}`).setNumberFormat('0');
s.getRange(`A7:C${end}`).format.horizontalAlignment='left';
s.getRange(`F7:F${end}`).format.horizontalAlignment='left';
s.getRange(`D7:E${end}`).format.horizontalAlignment='right';
s.getRange(`A7:F${end}`).format.rowHeight=30;
s.getRange(`B7:B${end}`).format.wrapText=true;
s.getRange(`F7:F${end}`).format.wrapText=true;
for(const [i,width] of [17,102,20,27,17,38].entries())s.getRange(`${String.fromCharCode(65+i)}1:${String.fromCharCode(65+i)}${end}`).format.columnWidth=width;
for(let i=0;i<rows.length;i++)if(rows[i][1].length>90)s.getRange(`A${i+7}:F${i+7}`).format.rowHeight=Math.ceil(rows[i][1].length/85)*16+8;
const t=s.tables.add(`A6:F${end}`,true,'ImagensAmbulatoriais');t.style='TableStyleMedium2';t.showFilterButton=true;
s.getRange('A6:F6').format={fill:'#17365D',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},rowHeight:34,wrapText:true,horizontalAlignment:'center',verticalAlignment:'center'};
s.freezePanes.freezeRows(6);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Imagens ambulatoriais!A6:F10',include:'values',tableMaxRows:5,tableMaxCols:6,maxChars:2000})).ndjson);
const preview=await wb.render({sheetName:s.name,range:'A1:F13',scale:1,format:'png'});
await fs.writeFile(`${root}/tmp/conversao/imagens-preview.png`,new Uint8Array(await preview.arrayBuffer()));
const out=await SpreadsheetFile.exportXlsx(wb);await out.save(path);
await fs.writeFile(`${root}/tmp/conversao/imagens-data.json`,JSON.stringify(rows));
console.log('COUNT',rows.length,'CATEGORIES',JSON.stringify(rows.reduce((a,r)=>(a[r[5]]=(a[r[5]]||0)+1,a),{})));
